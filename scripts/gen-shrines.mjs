const missing = prefectureOrder.filter(p => !raw.some(r => r[1] === p));
if (raw.length !== 100) { console.error(`件数が100件ではありません: ${raw.length}`); process.exit(1); }
if (missing.length) { console.error(`未収録の都道府県: ${missing.join(",")}`); process.exit(1); }

const slug = (i) => `shr-${String(i + 1).padStart(3, "0")}`;

// 画像は6枚の共通素材を割り当てる（神社ごとの画像ファイルを持たない）
const IMAGE_VARIANTS = 6;

const records = raw.map((r, i) => ({
  id: slug(i),
  name: r[0],
  prefecture: r[1],
  address: r[2],
  latitude: r[3],
  longitude: r[4],
  main_deity: r[5],
  description: r[6],
  image_url: `/images/shrine-${(i % IMAGE_VARIANTS) + 1}.webp`,
  visit_count: 180 + ((i * 977) % 3200),
}));

// 1行1神社のコンパクトJSON（差分レビューしやすい形）
const body = records
  .map((r) => "  " + JSON.stringify(r))
  .join(",\n");

mkdirSync("src/data", { recursive: true });
writeFileSync("src/data/shrines.json", `[\n${body}\n]\n`, "utf8");

console.log(
  `generated src/data/shrines.json : ${records.length} shrines / ` +
  `${new Set(records.map((r) => r.prefecture)).size} prefectures / ` +
  `${IMAGE_VARIANTS} shared images`,
);
